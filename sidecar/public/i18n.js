const LANG = MESSAGES[document.documentElement.lang] ? document.documentElement.lang : 'en-US';
const pluralRules = new Intl.PluralRules(LANG);

/**
 * Texto no idioma atual, com `{nome}` trocado por `params`. Com `params.count`, usa a forma
 * `<chave>_<categoria>` do Intl.PluralRules (one, few, many, other), caindo em `_other`.
 */
function t(key, params = {}) {
  const own = MESSAGES[LANG];
  const en = MESSAGES['en-US'];
  const text =
    'count' in params
      ? own[`${key}_${pluralRules.select(params.count)}`] ??
        own[`${key}_other`] ??
        en[`${key}_${new Intl.PluralRules('en-US').select(params.count)}`]
      : own[key] ?? en[key];
  return (text ?? key).replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const attr of ['title', 'placeholder', 'aria-label']) {
    const data = `i18n${attr.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}`;
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.dataset[data]));
  }
}
